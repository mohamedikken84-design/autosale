/**
 * Detect language automatically:
 * 1. Stored manual preference in localStorage
 * 2. Geo-IP location (async check) or browser navigator language
 */
export function getInitialLanguage(): Language {
  try {
    const saved = localStorage.getItem('auto_sale_lang') as Language;
    if (saved && ['nl', 'en', 'fr', 'de'].includes(saved)) {
      return saved;
    }
  } catch {
    // ignore
  }

  // Fallback to browser language
  if (typeof navigator !== 'undefined') {
    const navLang = navigator.language?.toLowerCase() || '';
    if (navLang.startsWith('nl')) return 'nl';
    if (navLang.startsWith('fr')) return 'fr';
    if (navLang.startsWith('de')) return 'de';
    if (navLang.startsWith('en')) return 'en';
  }

  return 'nl';
}

/**
 * Asynchronously detect country from IP and map to language if user hasn't chosen manually
 */
export async function detectLanguageFromGeoIP(): Promise<Language | null> {
  try {
    const res = await fetch('https://ipapi.co/json/', { signal: AbortSignal.timeout(2500) });
    if (!res.ok) return null;
    const data = await res.json();
    const country = (data.country_code || '').toUpperCase();

    if (country === 'BE' || country === 'NL') {
      // In Belgium, check if browser is French or Dutch
      if (navigator.language?.toLowerCase().startsWith('fr')) return 'fr';
      return 'nl';
    }
    if (country === 'FR' || country === 'LU') return 'fr';
    if (country === 'DE' || country === 'AT' || country === 'CH') return 'de';
    if (country === 'GB' || country === 'US' || country === 'IE') return 'en';

    return 'en';
  } catch {
    return null;
  }
}
